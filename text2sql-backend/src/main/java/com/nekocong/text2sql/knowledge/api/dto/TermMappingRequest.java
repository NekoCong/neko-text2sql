package com.nekocong.text2sql.knowledge.api.dto;

import com.nekocong.text2sql.knowledge.TermMapping;

/**
 * Request body for a business-term mapping.
 *
 * @param datasourceId the owning datasource
 * @param term the colloquial term
 * @param targetType {@code TABLE} or {@code COLUMN}
 * @param tableName the target table
 * @param columnName the target column (column mappings only), or {@code null}
 * @param description a short explanation, or {@code null}
 */
public record TermMappingRequest(
        String datasourceId,
        String term,
        String targetType,
        String tableName,
        String columnName,
        String description) {

    /**
     * Converts the request into a mapping (the id is generated by the repository).
     *
     * @return the mapping
     */
    public TermMapping toMapping() {
        return new TermMapping(null, datasourceId, term, targetType, tableName, columnName, description);
    }
}
